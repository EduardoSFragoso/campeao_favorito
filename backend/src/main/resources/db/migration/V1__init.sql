-- Esquema inicial, equivalente ao que o ddl-auto: update criou em produção até hoje.
-- A partir daqui, TUDO que muda o esquema entra como migração versionada (V+N__desc.sql):
-- nunca mais altere tabelas na mão nem confie no ddl-auto para isso.
-- Migrações não repetem: o Flyway guarda o histórico em flyway_schema_history.

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS favorites (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL,
    champion_id   VARCHAR(64) NOT NULL,
    champion_name VARCHAR(64) NOT NULL,
    title         VARCHAR(256),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_favorites_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_user_champion UNIQUE (user_id, champion_id)
);

-- findByUserIdOrderByCreatedAtDesc consulta por user_id — índice dedicado
CREATE INDEX IF NOT EXISTS idx_favorites_user_id ON favorites (user_id);
