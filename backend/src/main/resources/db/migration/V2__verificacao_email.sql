-- Verificação de e-mail (cadastro): usuário só entra depois de confirmar o dono do e-mail.
-- 1) users.email_verificado: quem JÁ existia antes desta migração entrou no sistema
--    sem verificação existente — marcar TRUE, senão o bloqueio de login trancaria
--    usuários reais.
-- 2) verificacao_email: guarda SOMENTE o hash SHA-256 do token (o cru nunca vai pro
--    banco), com expiração (24h) e uso único.

ALTER TABLE users ADD COLUMN email_verificado BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE users SET email_verificado = TRUE;

CREATE TABLE verificacao_email (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expira_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    usado_em   TIMESTAMP WITH TIME ZONE,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    -- CASCADE: pedidos de verificação pertencem ao usuário — remover a conta
    -- não pode ficar impedida por tokens pendentes (nem na limpeza de testes)
    CONSTRAINT fk_verificacao_user FOREIGN KEY (user_id) REFERENCES users (id)
        ON DELETE CASCADE
);

-- a checagem do token chega como hash — índice dedicado ao lookup
CREATE INDEX IF NOT EXISTS idx_verificacao_token_hash ON verificacao_email (token_hash);
