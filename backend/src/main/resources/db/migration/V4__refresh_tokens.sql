-- Refresh token (sessão longa, opção B do dono): token OPACO — o cru só existe na resposta do
-- login/refresh e no localStorage; o banco guarda SOMENTE o hash SHA-256. Rotação a cada troca
-- (o antigo vira revogado_em); REUSO de refresh revogado derruba a sessão inteira
-- (users.token_ver++, o JwtAuthFilter rejeita todo JWT velho). CASCADE: refreshes pertencem ao
-- usuário — remover a conta não pode ficar impedida por tokens pendentes.
CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expira_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    revogado_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES users (id)
        ON DELETE CASCADE
);

-- a troca do token chega como hash — índice dedicado ao lookup; o logout em massa usa user_id
CREATE INDEX IF NOT EXISTS idx_refresh_token_hash ON refresh_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_refresh_user_id ON refresh_tokens (user_id);
